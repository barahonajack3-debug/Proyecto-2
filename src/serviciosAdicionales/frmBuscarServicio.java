    private void btnacepActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnacepActionPerformed
     int F = tbTableSer.getSelectedRow();

    if (F == -1) {
        JOptionPane.showMessageDialog(this, "Seleccione un servicio");
    } else {
        try {
            int codigo = Integer.parseInt(tbTableSer.getValueAt(F, 0).toString());
            ServicioAdicional servicio = controlador.buscarServicio(codigo);
            frmServicio.cargarServicio(servicio);
            dispose();
        } catch (ServicioNoencontradoException NO) {
            JOptionPane.showMessageDialog(this, NO.getMessage());
        }
    }
    }//GEN-LAST:event_btnacepActionPerformed
    
    
   
