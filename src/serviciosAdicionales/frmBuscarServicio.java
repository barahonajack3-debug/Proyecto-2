    private void tablabuscar(){
        DefaultTableModel tabla = (DefaultTableModel) tbTableSer.getModel();
        tabla.setRowCount(0);
          for (ServicioAdicional servicio : controlador.getServicios()) {
            tabla.addRow(new Object[]{
            servicio.getCodigo(),
            servicio.getNombre(),
            servicio.getDescripcion(),
            servicio.getPrecio()
        });
    }
          }
    
    
    private void btnbuscActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnbuscActionPerformed
        try {
        int codigo = Integer.parseInt(txfcode.getText());
        ServicioAdicional servicio = controlador.buscarServicio(codigo);
        DefaultTableModel buscar = (DefaultTableModel) tbTableSer.getModel();
        buscar.setRowCount(0);

        buscar.addRow(new Object[]{
            servicio.getCodigo(),
            servicio.getNombre(),
            servicio.getDescripcion(),
            servicio.getPrecio()
        });

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El código debe ser un número");
    } catch (ServicioNoencontradoException F) {
        JOptionPane.showMessageDialog(this, F.getMessage());
    }
    }//GEN-LAST:event_btnbuscActionPerformed

